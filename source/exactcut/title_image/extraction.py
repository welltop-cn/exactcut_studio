PROMPT_VERSION = 1
MAX_IMAGE_BYTES = 32 * 1024 * 1024


def settings():
    return load_config()['title_extraction']


def root():
    return data_root() / 'title-assets'


def credentials(cfg):
    """Use the existing dedicated-credential-file pattern without global env writes."""
    file = Path(cfg['credentials_file']) if cfg.get('credentials_file') else project_env_file()
    protect_path(file)
    values = {}
    for line in file.read_text(encoding='utf-8-sig').splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, sep, value = line.removeprefix('export ').partition('=')
        if sep:
            values[key.strip()] = value.strip().strip("'\"")
    validate_env_owner(file, values)
    keys = ('OPENAI_API_KEY', 'OPENAI_BASE_URL', 'KES_LOGIN_EMAIL', 'KES_LOGIN_PASSWORD', 'KES_LOGIN_ENCRYPTED_PASSWORD')
    return {key: values.get(key, os.getenv(key, '')) for key in keys}


def check_drama(drama_id):
    if not re.fullmatch(r'[0-9]{6}', str(drama_id)):
        raise ValueError('剧 ID 必须为六位数字')
    return str(drama_id)


def poster_url(poster, base):
    if not isinstance(poster, str) or not poster.strip():
        raise ValueError('该剧没有封面地址')
    url = urljoin(base.rstrip('/') + '/', poster)
    parts, allowed = urlsplit(url), urlsplit(base)
    if (parts.scheme != 'https' or parts.netloc != allowed.netloc or parts.username or
            parts.password or parts.query or parts.fragment or not parts.path.startswith('/tb/') or
            '/image/' not in parts.path or '..' in parts.path):
        raise ValueError('封面地址不在已配置的图片来源中')
    return url


def decode_response(payload):
    if not isinstance(payload, dict) or not isinstance(payload.get('data'), list) or len(payload['data']) != 1:
        raise ValueError('图像接口没有返回一张图片')
    item = payload['data'][0]
    encoded = item.get('b64_json') if isinstance(item, dict) else None
    if not isinstance(encoded, str) or len(encoded) > MAX_IMAGE_BYTES * 4 // 3 + 8:
        raise ValueError('图像接口返回的图片格式或大小无效')
    try:
        raw = base64.b64decode(encoded, validate=True)
        validate_image(raw)
    except (OSError, SyntaxError) as exc:
        raise ValueError('图像接口返回的图片无法读取') from exc
    return raw


def validate_image(raw):
    if len(raw) > MAX_IMAGE_BYTES:
        raise ValueError('剧名图片过大')
    with Image.open(io.BytesIO(raw)) as image:
        if image.format != 'PNG' or image.width * image.height > 16_000_000:
            raise ValueError('剧名图片必须为有效 PNG')
        if 'A' not in image.getbands():
            raise ValueError('剧名图片没有真实透明通道，请重新提取')
        hist = image.getchannel('A').histogram()
        if hist[0] < image.width * image.height * .01 or not sum(hist[1:]):
            raise ValueError('剧名图片透明背景无效，请重新提取')


def store_asset(drama_id, raw, metadata):
    drama_id = check_drama(drama_id)
    validate_image(raw)
    sha = hashlib.sha256(raw).hexdigest()
    asset = json_sha256({'drama_id': drama_id, 'image_sha256': sha})
    folder = root() / asset
    folder.mkdir(parents=True, exist_ok=True)
    image = folder / 'title.png'
    # Identical generated bytes can repair a corrupt content-addressed asset too.
    fd, temporary = tempfile.mkstemp(prefix='title-', suffix='.tmp', dir=folder)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, image)
    finally:
        Path(temporary).unlink(missing_ok=True)
    write_json_atomic(folder / 'asset.json', {**metadata, 'drama_id': drama_id, 'image_sha256': sha})
    return asset


class AssetUnavailable(ValueError):
    """A previously stored asset cannot be read and may be regenerated."""


def asset_file(asset, drama_id):
    if not isinstance(asset, str) or not re.fullmatch(r'[0-9a-f]{64}', asset):
        raise ValueError('请先提取并确认剧名图片')
    try:
        folder = root() / asset
        meta = read_json(folder / 'asset.json')
        path = folder / 'title.png'
        if meta['drama_id'] != str(drama_id):
            raise ValueError('剧名图片与当前剧 ID 不符')
        if hashlib.sha256(path.read_bytes()).hexdigest() != meta['image_sha256']:
            raise AssetUnavailable('剧名图片文件已变化，需要重新提取')
        return path
    except (OSError, KeyError, TypeError, UnicodeError, json.JSONDecodeError) as exc:
        raise AssetUnavailable('剧名图片缺失或元数据无效，需要重新提取') from exc


def cached_reference(path, drama_id):
    """Invalid pointers or bytes are cache misses, never usable render inputs."""
    try:
        cached = read_json(path)
        asset_file(cached['asset'], drama_id)
        return cached
    except (OSError, ValueError, KeyError, TypeError):
        return None


def prompt(title):
    return (
        f'Extract ONLY the existing bottom title from this cover. Exact full title: {title!r}. '
        'Preserve the original letter shapes, thin stroke weights, colors, line breaks, proportions '
        'and spacing as faithfully as possible. Keep fine flourishes attached to the letters. '
        'Remove people, scenery, objects and background including between letters and inside holes. '
        'Exclude any separate top tagline. Do not bolden, recolor or redesign the title; do not add '
        'ornaments or words. Frame the complete title closely with a small transparent margin. '
        'Return true alpha transparency, no solid backdrop, colored haze or checkerboard.'
    )


def fetch_cover(client, drama_id, cfg, secrets):
    # This login and envelope are the existing, verified KES contract.
    login_values = [secrets.get(name, '') for name in ('KES_LOGIN_EMAIL', 'KES_LOGIN_PASSWORD', 'KES_LOGIN_ENCRYPTED_PASSWORD')]
    if not all(login_values):
        raise ValueError('尚未配置封面查询账号')
    base = cfg['kes_base_url'].rstrip('/')
    response = client.post(base + '/api/v1/user/session',
                           headers={'content-type': 'application/x-www-form-urlencoded', 'kes-service': 'op-mgr'},
                           json=dict(zip(('email', 'password', 'encrypted_passwd'), login_values)))
    response.raise_for_status()
    body = response.json()
    if body.get('code') != 2000 or not isinstance(body.get('data'), dict) or not isinstance(body['data'].get('user_token'), str):
        raise ValueError('封面查询登录失败')
    response = client.get(base + '/api/v3/ops/content/series-list',
                          headers={'Access-Token': body['data']['user_token']},
                          params={'page': 1, 'size': 100, 'series_id': drama_id})
    response.raise_for_status()
    body = response.json()
    data = body.get('data')
    if body.get('code') != 2000 or not isinstance(data, dict):
        raise ValueError('封面查询失败')
    rows = data.get('items')
    if (not isinstance(rows, list) or len(rows) != 1 or not isinstance(rows[0], dict) or
            rows[0].get('id') != int(drama_id) or data.get('has_more') is not False):
        raise ValueError('封面查询未返回唯一且匹配的剧 ID')
    row = rows[0]
    if not isinstance(row.get('name'), str) or not row['name'].strip():
        raise ValueError('封面查询缺少剧名')
    url = poster_url(row.get('poster'), cfg['poster_base_url'])
    chunks, size = [], 0
    with client.stream('GET', url) as response:
        response.raise_for_status()
        for chunk in response.iter_bytes():
            size += len(chunk)
            if size > MAX_IMAGE_BYTES:
                raise ValueError('封面图片过大')
            chunks.append(chunk)
    raw = b''.join(chunks)
    with Image.open(io.BytesIO(raw)) as im:
        im.verify()
    return row['name'], url, raw


def cover_connection(cfg):
    """Optional scoped DNS override; retain the original HTTP host and TLS identity."""
    address = cfg.get('kes_connect_ip', '')
    if address:
        address = str(ipaddress.ip_address(address))
    host = urlsplit(cfg['kes_base_url']).hostname

    def route(request):
        if address and request.url.host == host:
            request.headers['Host'] = request.url.netloc.decode('ascii')
            request.extensions['sni_hostname'] = host
            request.url = request.url.copy_with(host=address)
    return route


def fetch_cover_with_retry(client, drama_id, cfg, secrets):
    for attempt in range(3):
        try:
            return fetch_cover(client, drama_id, cfg, secrets)
        except httpx.TransportError as exc:
            if attempt == 2:
                raise RuntimeError('查询或下载剧封面时网络连接失败，已重试 3 次；请检查封面服务连接') from exc
            time.sleep(attempt + 1)


def extract(drama_id, force=False):
    drama_id = check_drama(drama_id)
    cfg = settings()
    if not cfg['enabled']:
        raise ValueError('封面剧名提取尚未启用')
    # Existing assets remain usable offline. Live runs also check cover changes.
    latest = root() / f'{drama_id}.json'
    if latest.exists() and not force and not cfg.get('allow_live_requests'):
        cached = cached_reference(latest, drama_id)
        if cached:
            return cached['asset']
    if not cfg.get('allow_live_requests') or environment() not in {'production', 'development'}:
        raise ValueError('剧名图片实时提取未启用；需要独立配置 title_extraction.allow_live_requests')
    secrets = credentials(cfg)
    key = secrets.get('OPENAI_API_KEY', '')
    if not key:
        raise ValueError('尚未配置图像编辑 API')
    root().mkdir(parents=True, exist_ok=True)
    # Serialize each drama's check/generation to avoid duplicate paid requests;
    # unrelated dramas can proceed under the existing worker concurrency limits.
    with (root() / f'generation-{drama_id}.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        with httpx.Client(timeout=httpx.Timeout(cfg['timeout_seconds'], connect=10), follow_redirects=False,
                          event_hooks={'request': [cover_connection(cfg)]}) as client:
            title, url, cover = fetch_cover_with_retry(client, drama_id, cfg, secrets)
            cover_sha = hashlib.sha256(cover).hexdigest()
            text = prompt(title)
            identity = {'cover_sha256': cover_sha, 'model': cfg['model'], 'prompt_version': PROMPT_VERSION,
                        'prompt_sha256': hashlib.sha256(text.encode('utf-8')).hexdigest(), 'quality': cfg['quality']}
            if latest.exists() and not force:
                cached = cached_reference(latest, drama_id)
                if cached and all(cached.get(key) == value for key, value in identity.items()):
                    return cached['asset']
            with Image.open(io.BytesIO(cover)) as source:
                mime = Image.MIME.get(source.format)
            if mime not in {'image/png', 'image/jpeg', 'image/webp'}:
                raise ValueError('封面格式不支持图片编辑')
            body = {'model': cfg['model'], 'images': [{'image_url': f'data:{mime};base64,' + base64.b64encode(cover).decode()}],
                    'prompt': text, 'background': 'transparent', 'output_format': 'png', 'quality': cfg['quality'], 'size': 'auto'}
            response = client.post((secrets.get('OPENAI_BASE_URL') or 'https://api.openai.com/v1').rstrip('/') + '/images/edits',
                                   headers={'Authorization': 'Bearer ' + key}, json=body)
            response.raise_for_status()
            raw = decode_response(response.json())
        asset = store_asset(drama_id, raw, {**identity, 'title': title, 'cover_url': url, 'prompt': text})
        write_json_atomic(latest, {'asset': asset, **identity})
        return asset


def prepare_manifest(manifest, batch_dir):
    """Resolve automatic images before fingerprints; pin the choice for retries."""
    requests = []
    for request in manifest.requests:
        brand = request.brand_overlay
        if not brand.title_enabled or brand.title_mode != 'cover':
            requests.append(request)
            continue
        drama_id = manifest.drama_id
        if brand.title_asset:
            try:
                asset_file(brand.title_asset, drama_id)
                requests.append(request)
                continue
            except AssetUnavailable:
                brand = brand.model_copy(update={'title_asset': ''})
        identity = json_sha256({'drama_id': drama_id, 'brand': brand.model_dump()})
        folder = Path(batch_dir) / 'title-assets'
        folder.mkdir(parents=True, exist_ok=True)
        pin = folder / f'{identity}.json'
        with (folder / f'{identity}.lock').open('a') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            cached = cached_reference(pin, drama_id)
            if cached:
                asset = cached['asset']
            else:
                asset = extract(drama_id)
                write_json_atomic(pin, {'asset': asset, 'drama_id': drama_id})
        resolved = brand.model_copy(update={'title_asset': asset, 'title_drama_id': drama_id})
        requests.append(request.model_copy(update={'brand_overlay': resolved}))
    return manifest.model_copy(update={'requests': requests})
